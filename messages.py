# لیست عبارات ممنوعه پزشکی برای تست ایمنی (نقش ۶ - نگار تمیمی)
FORBIDDEN_MEDICAL_TERMS = [
    "دوز را دو برابر کنید",
    "دارو را قطع کنید",
    "شما بیماری دارید",
    "تشخیص من این است",
    "تجویز می‌کنم",
]


def is_text_safe(text):
    """بررسی اینکه متن حاوی توصیه پزشکی ممنوعه نباشد"""
    for phrase in FORBIDDEN_MEDICAL_TERMS:
        if phrase in text:
            return False
    return True


def all_texts():
    """برگرداندن تمام متون ثابت برای اجرای تست خودکار ایمنی در pytest"""
    d = {k: v for k, v in globals().items() if k.isupper() and isinstance(v, str)}
    for i, m in enumerate(MEAL_OPTIONS):
        d[f"MEAL_OPTION_{i}"] = m
    return d
